    /**
     * Split a class attribute into tokens, keeping `{…}` expressions whole.
     *
     * @return list<string>
     */
    private static function classTokens(string $value): array
    {
        $tokens = [];
        $current = '';
        $depth = 0;
        foreach (str_split($value) as $char) {
            if ($char === '{') {
                $depth++;
            } elseif ($char === '}') {
                $depth = max(0, $depth - 1);
            }
            if ($depth === 0 && trim($char) === '') {
                if ($current !== '') {
                    $tokens[] = $current;
                    $current = '';
                }
                continue;
            }
            $current .= $char;
        }
        if ($current !== '') {
            $tokens[] = $current;
        }

        /*
         * A class an inline f:if chooses is still a class. `{f:if(condition: …,
         * then: 'asc', else: 'desc')}` is one token by the rule above, and
         * `asc` and `desc` were hiding inside it — so every single-quoted
         * literal in an expression is split out and judged as well. A literal
         * that is not a class name (a label, a link target) is harmless: it is
         * checked against the same prefixes and a sentence is not a class.
         */
        foreach ($tokens as $token) {
            if (!str_starts_with($token, '{') && !str_contains($token, '{')) {
                continue;
            }
            if (!preg_match_all("#'([^']*)'#", $token, $literals)) {
                continue;
            }
            foreach ($literals[1] as $literal) {
                foreach (preg_split('#\s+#', trim($literal)) ?: [] as $word) {
                    if ($word !== '' && preg_match('#^[a-zA-Z][a-zA-Z0-9_-]*$#', $word) === 1) {
                        $tokens[] = $word;
                    }
                }
            }
        }

        return $tokens;
    }

    /**
     * Every class attribute in a file, as [value, line].
     *
     * `f:variable` bodies count as class attributes too. Two elements used to
     * assemble `astryx-grid cols-3` and `astryx-item align-start` into a
     * variable and interpolate the result, which is the same thing as writing
     * the classes — and it slipped past this scan for a year, long enough for
     * every modifier in those strings to stop matching anything.
     *
     * @return list<array{0: string, 1: string}>
     */
    private static function classAttributes(string $source): array
    {
        $source = (string)preg_replace('#<f:comment>.*?</f:comment>#s', '', $source);

        $found = [];
        $patterns = [
            '#class="([^"]*)"#s',
            '#<f:variable\s+name="[^"]*(?:[Cc]lass|Surface)"\s*>(.*?)</f:variable>#s',
        ];
        foreach ($patterns as $pattern) {
            if (!preg_match_all($pattern, $source, $matches, PREG_OFFSET_CAPTURE)) {
                continue;
            }
            foreach ($matches[1] as $match) {
                $line = substr_count(substr($source, 0, $match[1]), "\n") + 1;
                // A variable body holds ViewHelper tags around the class names;
                // the names are what is being looked for, so the tags go.
                $found[] = [trim((string)preg_replace('#<[^>]*>#', ' ', $match[0])), (string)$line];
            }
        }

        return $found;
    }

