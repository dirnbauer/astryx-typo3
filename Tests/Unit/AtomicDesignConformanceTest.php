/**
 * The atomic-design contract, enforced.
 *
 * A design system that is only a convention decays: the first template that
 * writes `class="astryx-button primary"` because it is quicker costs nothing,
 * and the two hundredth makes the system unmaintainable. Everything the 2.0
 * refactor established is asserted here instead of documented and hoped for.
 *
 * What these rules read is the filesystem. Three of them used to compare
 * Build/Data/component-contract.json against the components it described, which
 * only ever caught the file being out of date with the directory it was written
 * from; both JSON files are generated by
 * Build/Scripts/sync-component-contract.mjs now, and `npm run build` plus CI's
 * `git diff --exit-code` is what keeps them current.
